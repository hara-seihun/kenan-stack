#!/bin/bash
# Small host-only install, shared by fresh hosts, normal deploys and independent updaters.
set -euo pipefail
cd "$(dirname "$0")/.."
(( EUID == 0 )) || { echo 'runtime_control_install_requires_root' >&2; exit 1; }
# Root tools (visudo, useradd) live in sbin, which an inherited PATH may omit: the Acme intake's PATH did (2026-11-04).
for dir in /usr/local/sbin /usr/sbin /sbin; do if [[ -d $dir && :$PATH: != *:$dir:* ]]; then PATH=$dir:$PATH; fi; done; export PATH
source deploy/place.sh
mkdir -p /usr/local/sbin /usr/local/lib/kenan /etc/systemd/system /etc/sudoers.d
place 0644 deploy/runtime-reload.mjs /usr/local/lib/kenan/runtime-reload.mjs
place 0755 deploy/kenan-runtime-restart /usr/local/sbin/kenan-runtime-restart
place 0755 deploy/kenan-runtime-recover /usr/local/sbin/kenan-runtime-recover
units_changed=0
place_unit 0644 deploy/kenan@.service /etc/systemd/system/kenan@.service
for unit in kenan-runtime-recovery.{service,timer}; do place_unit 0644 "deploy/$unit" "/etc/systemd/system/$unit"; done
# Grant only this command, to each locally hosted Unix owner and existing household operators.
# Read the installed configuration: standalone hosts need not have a kenan user or operators group.
grant=$(mktemp /etc/sudoers.d/.kenan-runtime-restart.XXXXXX)
trap 'rm -f "$grant"' EXIT
python3 - > "$grant" <<'PY'
import grp, json, pathlib, pwd, re
owners = set()
for channel in ('beta', 'production'):
    path = pathlib.Path('/etc/kenan') / (channel + '.json')
    if not path.exists():
        continue
    for person in json.loads(path.read_text())['people']:
        if (person.get('manager') or {}).get('elsewhere'):
            continue
        user = person['unixUser']
        if not re.fullmatch(r'[a-z_][a-z0-9_-]*', user):
            raise SystemExit('runtime_control_invalid_unix_user: ' + repr(user))
        pwd.getpwnam(user)
        owners.add(user)
try:
    grp.getgrnam('kenan-operators')
    owners.add('%kenan-operators')
except KeyError:
    pass
print('# Generated by deploy/install-runtime-control.sh from locally hosted owners.')
for owner in sorted(owners):
    print(owner + ' ALL=(root) NOPASSWD: /usr/local/sbin/kenan-runtime-restart beta, /usr/local/sbin/kenan-runtime-restart production')
PY
chmod 0440 "$grant"
visudo -cqf "$grant"
mv -fT "$grant" /etc/sudoers.d/kenan-runtime-restart
if (( units_changed )); then systemctl daemon-reload; fi
enable_units --now kenan-runtime-recovery.timer
