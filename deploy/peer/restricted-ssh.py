#!/usr/bin/python3
"""SSH forced command: allow one peer relay, never a shell or another socket."""
import json
import os
import re
import shlex
import subprocess
import sys
from urllib.parse import parse_qs, urlsplit


def main():
    channel, person, peer = sys.argv[1:]
    if channel not in ("beta", "production") or any(
        not re.fullmatch(r"[a-z][a-z0-9-]{0,39}", value) for value in (person, peer)
    ):
        raise ValueError("expected channel, person and peer")
    socket = f"/run/kenan/{channel}-peer/{person}.sock"
    args = shlex.split(os.environ.get("SSH_ORIGINAL_COMMAND", ""))
    status = ["systemctl", "show", f"kenan@{channel}.service", "-p", "ActiveState", "-p", "UnitFileState"]
    if args == status:
        return subprocess.call(["/usr/bin/systemctl", *args[1:]], stdin=subprocess.DEVNULL)
    # This is the command generated by peer-relay.mjs. Do not pass any unvalidated
    # option through to curl; even curl's config/environment can change its target.
    if len(args) < 10 or args[:4] != ["curl", "--silent", "--show-error", "--max-time"]:
        raise ValueError("only peer relay requests are allowed")
    timeout = int(args[4])
    if not 1 <= timeout <= 60 or args[5:8] != ["--unix-socket", socket, "-X"]:
        raise ValueError("invalid timeout or socket")
    method = args[8]
    url = urlsplit(args[-1])
    if url.scheme != "http" or url.netloc != "localhost" or url.fragment:
        raise ValueError("invalid relay URL")
    body = None
    if method == "GET":
        if len(args) != 10 or url.path != "/outbox":
            raise ValueError("only the peer outbox may be read")
        query = parse_qs(url.query, strict_parsing=True)
        if set(query) != {"peer", "wait"} or query["peer"] != [peer] or len(query["wait"]) != 1 or not 0 <= int(query["wait"][0]) <= 25:
            raise ValueError("invalid outbox peer or wait")
    elif method == "POST":
        if len(args) != 14 or args[9:13] != ["-H", "content-type: application/json", "--data-binary", "@-"] or url.path not in ("/inbox", "/ack") or url.query:
            raise ValueError("only peer delivery and acknowledgement are allowed")
        body = sys.stdin.buffer.read(1024 * 1024 + 1)
        if len(body) > 1024 * 1024 or json.loads(body).get("peer") != peer:
            raise ValueError("invalid request size or peer")
    else:
        raise ValueError("invalid relay method")
    command = ["/usr/bin/curl", "--disable", "--silent", "--show-error", "--max-time", str(timeout), "--unix-socket", socket, "-X", method]
    if body is not None:
        command += ["-H", "content-type: application/json", "--data-binary", "@-"]
    command.append(args[-1])
    return subprocess.run(command, input=body, env={"PATH": "/usr/bin:/bin"}).returncode


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, TypeError, KeyError) as error:
        print(f"peer_relay_request_refused: {error}", file=sys.stderr)
        sys.exit(1)
