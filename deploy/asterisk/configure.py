#!/usr/bin/env python3
"""Writes Asterisk's configuration and the SIP firewall for Kenan's phone lines from the people's telephone settings.

Source of truth: `media.telephone` in /etc/kenan/domains/*.json with provider "sip-trunk". Asterisk runs where the
line's call bridges run (`media.telephone.bridge`): on assistant-host for "local", on the phone edge for "edge" (written
there over SSH, /etc/kenan/phone-edge.json). Each line becomes one PJSIP endpoint `line-<digits>`: calls from the
carrier's signalling networks (`sip.from`) are identified by source address and dialled to the DID (the dialplan sees
the called number); when the carrier has issued an account (`sip.outbound.kind == "register"`) Asterisk also registers
it and places outbound calls through it. ARI listens only where Kenan reaches it: 127.0.0.1 locally, the edge's mesh
address on the edge. Its password is created once per host in the line's `ariConfigPath` (root 0600): url, user,
password, read by Kenan Stack and handed to each call's bridge. SIP (port 5060) is accepted only from the carriers'
networks: nftables table `inet kenan_sip` in /etc/kenan/sip-firewall.nft, loaded at boot by kenan-sip-firewall.service.
Run as root: deploy/asterisk/configure.py [--check] [--domains DIR] (DIR: a scratch set of domain files for a test
line). Reloads Asterisk and the firewall on each host whose files changed.
"""
import json, os, re, secrets, subprocess, sys
from pathlib import Path

DOMAINS = Path('/etc/kenan/domains')
EDGE = Path('/etc/kenan/phone-edge.json')
LOCAL_PUBLIC_IP = '62.238.90.47'
ETC = '/etc/asterisk'
FIREWALL = '/etc/kenan/sip-firewall.nft'
FIREWALL_UNIT = '/etc/systemd/system/kenan-sip-firewall.service'


def lines(domains):
    found = []
    for path in sorted(domains.glob('*.json')):
        media = json.loads(path.read_text()).get('media') or {}
        t = media.get('telephone') or {}
        if t.get('kind') != 'configured' or t.get('provider') != 'sip-trunk':
            continue
        sip = t['sip']
        outbound = sip['outbound']
        bridge = t['bridge']['kind']
        if bridge not in ('local', 'edge'):
            raise SystemExit(f'{path}: media.telephone.bridge.kind must be "local" or "edge"')
        if outbound['kind'] == 'edge':
            if bridge != 'edge' or set(outbound) != {'kind'}:
                raise SystemExit(f'{path}: sip.outbound.kind=edge requires an edge bridge and no local registration settings')
            # This host uses a line managed by the edge owner. Never regenerate its shared Asterisk configuration.
            continue
        line = {'person': path.stem, 'did': t['fromNumber'], 'from': sip['from'], 'register': None, 'host': bridge, 'ari': t['ariConfigPath']}
        if outbound['kind'] == 'register':
            password = Path(outbound['passwordPath']).read_text().strip()
            if not password:
                raise SystemExit(f'{path}: empty SIP password at {outbound["passwordPath"]}')
            line['register'] = {'server': outbound['server'], 'user': outbound['username'], 'password': password}
        elif outbound['kind'] != 'none':
            raise SystemExit(f'{path}: sip.outbound.kind must be "register" or "none"')
        found.append(line)
    return found


def ari_secret(path, url):
    path = Path(path)
    if path.exists():
        value = json.loads(path.read_text())
        if value.get('url') == url:
            return value
        value['url'] = url
    else:
        value = {'url': url, 'user': 'kenan', 'password': secrets.token_hex(24)}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(value, indent=2) + '\n')
    os.chmod(path, 0o600)
    return value


def pjsip(found, public_ip):
    out = [
        '; Generated by kenan-stack deploy/asterisk/configure.py from /etc/kenan/domains/*.json. Do not edit.',
        '[kenan-udp]', 'type=transport', 'protocol=udp', 'bind=0.0.0.0:5060',
        f'external_media_address={public_ip}', f'external_signaling_address={public_ip}', '',
    ]
    for line in found:
        digits = line['did'].lstrip('+')
        name = f'line-{digits}'
        reg = line['register']
        endpoint = [f'[{name}]', 'type=endpoint', 'transport=kenan-udp', 'context=kenan-inbound', 'disallow=all', 'allow=ulaw',
                    'direct_media=no', 'rtp_symmetric=yes', 'force_rport=yes', 'rewrite_contact=yes', 'dtmf_mode=rfc4733',
                    'trust_id_inbound=yes', 'send_rpid=no', 'send_pai=no', f'callerid=<{digits}>']
        if reg:
            server = reg['server']  # host, or host:port when the carrier listens elsewhere than 5060
            domain = server.rsplit(':', 1)[0]
            out += [
                f'[{name}-auth]', 'type=auth', 'auth_type=userpass', f'username={reg["user"]}', f'password={reg["password"]}', '',
                f'[{name}]', 'type=registration', 'transport=kenan-udp', f'outbound_auth={name}-auth',
                f'server_uri=sip:{server}', f'client_uri=sip:{reg["user"]}@{domain}', f'contact_user={digits}',
                'expiration=300', 'retry_interval=20', 'forbidden_retry_interval=120', 'max_retries=100000', 'line=yes', f'endpoint={name}', '',
                f'[{name}]', 'type=aor', f'contact=sip:{server}', 'qualify_frequency=60', '',
            ]
            endpoint += [f'outbound_auth={name}-auth', f'aors={name}', f'from_user={reg["user"]}', f'from_domain={domain}']
        out += endpoint + ['']
        out += [f'[{name}]', 'type=identify', f'endpoint={name}'] + [f'match={cidr}' for cidr in line['from']] + ['']
    out.append('#tryinclude pjsip_local.conf')
    return '\n'.join(out) + '\n'


EXTENSIONS = """; Generated by kenan-stack deploy/asterisk/configure.py. Do not edit.
; A call to one of Kenan's DIDs goes to the Stasis app of the Kenan channel that answers that line. Each channel sets
; GLOBAL(KENAN_LINE_<digits>) over ARI when it connects; with no channel connected the call is refused (the carrier
; then sends it to its voicemail). The DID may arrive with a leading +.
[general]
static=yes
writeprotect=yes

[kenan-inbound]
exten => _+X.,1,Goto(${EXTEN:1},1)
exten => _X.,1,Set(KENAN_APP=${GLOBAL(KENAN_LINE_${EXTEN})})
 same => n,GotoIf($["${KENAN_APP}" = ""]?down)
 same => n,Stasis(${KENAN_APP},${EXTEN},${CALLERID(num)})
 same => n,Hangup()
 same => n(down),Hangup(34)

[default]
exten => _X.,1,Hangup(21)

#tryinclude extensions_local.conf
"""

MODULES = """; Generated by kenan-stack deploy/asterisk/configure.py. Do not edit.
[modules]
autoload=yes
noload => chan_iax2.so
noload => chan_mgcp.so
noload => chan_unistim.so
noload => chan_skinny.so
noload => chan_ooh323.so
noload => chan_motif.so
noload => res_xmpp.so
noload => pbx_dundi.so
noload => res_hep.so
noload => res_hep_pjsip.so
noload => res_hep_rtcp.so
noload => cdr_custom.so
noload => cdr_manager.so
noload => cel_custom.so
noload => cel_manager.so
noload => res_pjsip_phoneprov_provider.so
noload => res_phoneprov.so
noload => pbx_ael.so
"""


UNIT = """[Unit]
Description=Kenan phone lines: SIP only from the carriers (kenan-stack deploy/asterisk/configure.py)
Before=asterisk.service
After=nftables.service

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=/usr/sbin/nft -f /etc/kenan/sip-firewall.nft
ExecStop=/usr/sbin/nft delete table inet kenan_sip

[Install]
WantedBy=multi-user.target
"""


def firewall(found):
    nets = sorted({cidr for line in found for cidr in line['from']})
    allowed = f'ip saddr {{ {", ".join(nets)} }} accept'
    return '\n'.join([
        '# Generated by kenan-stack deploy/asterisk/configure.py: SIP only from the phone lines\' carriers.',
        'table inet kenan_sip', 'delete table inet kenan_sip',
        'table inet kenan_sip {', '  chain input {', '    type filter hook input priority -5; policy accept;',
        '    iifname "lo" accept',
        f'    udp dport 5060 {allowed}', f'    tcp dport 5060 {allowed}',
        '    udp dport 5060 drop', '    tcp dport 5060 drop',
        '  }', '}', ''])


def render(found, public_ip, bind, ari):
    """Every file this host needs, by absolute path."""
    etc = {
        'pjsip.conf': pjsip(found, public_ip),
        'extensions.conf': EXTENSIONS,
        'modules.conf': MODULES,
        'http.conf': f'[general]\nenabled=yes\nbindaddr={bind}\nbindport=8088\n',
        'ari.conf': f'[general]\nenabled=yes\nallowed_origins=\n\n[{ari["user"]}]\ntype=user\nread_only=no\npassword={ari["password"]}\n\n#tryinclude ari_local.conf\n',
        'rtp.conf': '[general]\nrtpstart=10000\nrtpend=20000\nstrictrtp=seqno\nicesupport=no\nstunaddr=\n',
        'manager.conf': '[general]\nenabled=no\n',
        'iax.conf': '[general]\n',
    }
    files = {f'{ETC}/{name}': text for name, text in etc.items()}
    files[FIREWALL] = firewall(found)
    files[FIREWALL_UNIT] = UNIT
    return files


def apply(files, check):
    """Writes the changed files on this host and reloads what they belong to. Returns the changed paths."""
    # The shared edge has lines owned on more than one host. A partial domain directory must not erase a neighbour.
    pjsip_path = f'{ETC}/pjsip.conf'
    if pjsip_path in files and Path(pjsip_path).exists():
        endpoints = lambda text: set(re.findall(r'^\[(line-\d+)\]\ntype=endpoint$', text, re.M))
        missing = endpoints(Path(pjsip_path).read_text()) - endpoints(files[pjsip_path])
        if missing:
            raise SystemExit(f'asterisk_incomplete_domains: configuration omits existing endpoints {sorted(missing)}; regenerate from the shared edge owner with every line included')
    changed = [p for p, text in files.items() if not (Path(p).exists() and Path(p).read_text() == text)]
    if check:
        return changed
    media = Path(__file__).with_name('install-media.py')
    if not media.exists():
        media = Path('/usr/local/lib/kenan/asterisk-media/install-media.py')
    subprocess.run(['python3', str(media), 'apply'], check=True, stdout=sys.stderr)
    if not changed:
        return changed
    for p in changed:
        Path(p).parent.mkdir(parents=True, exist_ok=True)
        Path(p).write_text(files[p])
        if p.startswith(ETC + '/'):
            os.chmod(p, 0o640)
            subprocess.run(['chgrp', 'asterisk', p], check=True)
    if FIREWALL_UNIT in changed:
        subprocess.run(['systemctl', 'daemon-reload'], check=True)
        subprocess.run(['systemctl', 'enable', 'kenan-sip-firewall.service'], check=True)
    if FIREWALL in changed:
        subprocess.run(['nft', '-f', FIREWALL], check=True)
    if any(p in changed for p in (f'{ETC}/modules.conf', f'{ETC}/http.conf')):
        subprocess.run(['systemctl', 'restart', 'asterisk'], check=True)
    elif any(p.startswith(ETC + '/') for p in changed):
        subprocess.run(['asterisk', '-rx', 'core reload'], check=True)
    return changed


def edge_ssh(edge):
    return ['ssh', '-i', edge['sshKeyPath'], '-o', f'UserKnownHostsFile={edge["knownHostsPath"]}', '-o', 'StrictHostKeyChecking=yes',
            '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=10', f'{edge["user"]}@{edge["host"]}']


def main():
    if '--apply-stdin' in sys.argv:
        payload = json.load(sys.stdin)
        print(json.dumps(apply(payload['files'], payload['check'])))
        return
    check = '--check' in sys.argv
    domains = Path(sys.argv[sys.argv.index('--domains') + 1]) if '--domains' in sys.argv else DOMAINS
    found = lines(domains)
    report = {}
    for host in ('local', 'edge'):
        mine = [l for l in found if l['host'] == host]
        if not mine:
            continue
        paths = {l['ari'] for l in mine}
        if len(paths) != 1:
            raise SystemExit(f'lines on the {host} Asterisk name different ariConfigPath files: {sorted(paths)}')
        if host == 'local':
            ari = ari_secret(paths.pop(), 'http://127.0.0.1:8088')
            report[host] = apply(render(mine, LOCAL_PUBLIC_IP, '127.0.0.1', ari), check)
            continue
        edge = json.loads(EDGE.read_text())
        ari = ari_secret(paths.pop(), f'http://{edge["host"]}:8088')
        payload = json.dumps({'files': render(mine, edge['publicAddress'], edge['host'], ari), 'check': check})
        ssh = edge_ssh(edge)
        subprocess.run(ssh + ['install -d -m 755 /usr/local/lib/kenan/asterisk-media && cat > /usr/local/lib/kenan/asterisk-configure.py'], input=Path(__file__).read_bytes(), check=True)
        for name in ('install-media.py', 'negotiated-media-learning.patch'):
            subprocess.run(ssh + [f'cat > /usr/local/lib/kenan/asterisk-media/{name}'], input=Path(__file__).with_name(name).read_bytes(), check=True)
        out = subprocess.run(ssh + ['python3 /usr/local/lib/kenan/asterisk-configure.py --apply-stdin'], input=payload.encode(), check=True, capture_output=True)
        report[host] = json.loads(out.stdout)
    print(json.dumps({'lines': {l['did']: l['host'] for l in found}, 'changed': report, 'check': check}))


if __name__ == '__main__':
    main()
