import { chromium } from 'playwright-core';
import { readFile } from 'node:fs/promises';
const [origin, cookies] = process.argv.slice(2);
const token = (await readFile(cookies, 'utf8')).trim().split('\t').at(-1);
const host = new URL(origin).hostname;
const b = await chromium.launch({ executablePath: '/srv/kenan/toolchains/chrome-154.0.8037.92/chrome' });
const c = await b.newContext({ viewport: { width: 412, height: 915 }, isMobile: true });
await c.addCookies([{ name: 'kenan_session', value: token, domain: host, path: '/', secure: true, httpOnly: true, sameSite: 'Lax' }]);
const p = await c.newPage(); const errors = [];
p.on('console', m => { if (m.type() === 'error' || m.type() === 'warning') errors.push(m.text()); }); p.on('pageerror', e => errors.push('pageerror ' + e.message));
await p.goto(origin + '/'); await p.waitForFunction(() => document.documentElement.dataset.live === 'true', null, { timeout: 15000 });
await p.waitForTimeout(1500);
const info = await p.evaluate(() => ({ title: document.querySelector('.topbar h1')?.textContent, conn: document.querySelector('.connection')?.textContent, msgs: document.querySelectorAll('.transcript article.message').length, tools: document.querySelectorAll('.tool-card').length, sw: !!navigator.serviceWorker.controller, snap: (localStorage.getItem('kenan-startup-v1') ?? '').length }));
console.log(JSON.stringify(info));
await p.locator('.tool-card summary').last().click(); await p.waitForTimeout(800);
console.log('tool body chars', (await p.locator('.tool-card .tool-body').last().innerText()).length);
await p.screenshot({ path: '/home/kenan/.cache/app-fast-load/smoke.png' });
await p.reload(); await p.waitForFunction(() => document.documentElement.dataset.live === 'true', null, { timeout: 15000 });
console.log('after reload controlled', await p.evaluate(() => !!navigator.serviceWorker.controller));
console.log('errors', errors);
await b.close();
